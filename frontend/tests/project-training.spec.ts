  await page.goto(`/?project_run=${process.env.PROJECT_TRAINING_RUN_ID}`)
  const route = page.getByRole("region", { name: "项目模块学习路线", exact: true })
  await expect(route).toBeVisible()
  await route.getByRole("checkbox", { name: "允许发送项目模块片段" }).check()
  let lost = false
  await page.route("**/api/v1/project-training/analyze", async request => {
    if (lost) { await request.continue(); return }
    lost = true
    const response = await request.fetch()
    expect(response.status()).toBe(202)
    await request.abort("failed")
  })
  await route.getByRole("button", { name: "分析模块学习路线（不开题）" }).click()
  await expect(route.getByRole("alert")).toContainText("操作未确认成功")
  await route.getByRole("button", { name: "重新读取项目路线" }).click()
  await expect(route.getByLabel("模块训练重点")).toBeVisible({ timeout: 15000 })
  await expect(route.getByRole("button", { name: "开始模块教学练习" })).toBeDisabled()
