  let arrived!: () => void
  const accepted = new Promise<void>(resolve => { arrived = resolve })
  let started = ""
  await page.route("**/api/v1/topics/*/start", async request => {
    const response = await request.fetch()
    expect(response.status()).toBe(202)
    started = (await response.json()).id
    arrived()
    await gate
    await request.fulfill({ response })
  })
  const response = page.waitForResponse(r => r.url().includes("/topics/") && r.url().endsWith("/start"))
  await route.getByRole("button", { name: "开始模块教学练习" }).click()
  await accepted
  await page.getByLabel("查看已有项目任务").selectOption(process.env.PROJECT_TRAINING_OTHER_ID!)
