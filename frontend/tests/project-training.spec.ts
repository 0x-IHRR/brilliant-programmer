  await expect(route.getByRole("button", { name: "确认模块路线（不生成题目）" })).toBeEnabled()
  await route.getByRole("button", { name: "确认模块路线（不生成题目）" }).focus(); await page.keyboard.press("Enter")
  await expect(route.getByRole("button", { name: "开始模块教学练习" })).toBeEnabled()
  await route.getByText("本次范围与缺项", { exact: true }).click()
  await expect(route).toContainText("未执行目标代码")
  await route.screenshot({ path: "test-results/project-training-320.png" })
  await page.evaluate(() => document.documentElement.style.fontSize = "200%")
  await route.getByRole("button", { name: "开始模块教学练习" }).scrollIntoViewIfNeeded()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: "test-results/project-training-200.png" })
  await page.evaluate(() => document.documentElement.style.fontSize = "")
  await route.getByRole("button", { name: "开始模块教学练习" }).click()
